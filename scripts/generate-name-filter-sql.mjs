// Prints the SQL for public.name_skeleton() and public.is_name_allowed() from
// lib/domain/name-filter-terms.json, so the database filter uses exactly the
// same vocabulary as the client (lib/domain/name-filter.ts).
//
//   node scripts/generate-name-filter-sql.mjs > fragment.sql
//
// To change the vocabulary: edit the JSON, run this script and put the output
// into a NEW migration (never edit an applied one).
import { readFileSync } from "node:fs";

const terms = JSON.parse(
  readFileSync(new URL("../lib/domain/name-filter-terms.json", import.meta.url), "utf8"),
);
const flatten = (groups) => Object.values(groups).flat();
const quote = (value) => `'${value.replaceAll("'", "''")}'`;
const array = (values) => `array[${values.map(quote).join(", ")}]::text[]`;

let katakana = "";
let hiragana = "";
for (let code = 0x30a1; code <= 0x30f6; code += 1) {
  katakana += String.fromCodePoint(code);
  hiragana += String.fromCodePoint(code - 0x60);
}

const keepClass = "a-z0-9\\u3041-\\u3096\\u30fc\\u3400-\\u4dbf\\u4e00-\\u9fff";

console.log(`-- Generated by scripts/generate-name-filter-sql.mjs from lib/domain/name-filter-terms.json.
-- Same normalization as toSkeleton() in lib/domain/name-filter.ts:
-- NFKC, lower case, katakana to hiragana, digit look-alikes, then keep only
-- ASCII letters/digits, hiragana, the long vowel mark and kanji.
create or replace function public.name_skeleton(p_name text)
returns text
language sql
immutable
set search_path = ''
as $$
  select regexp_replace(
    translate(
      translate(
        lower(normalize(coalesce(p_name, ''), NFKC)),
        ${quote(katakana)},
        ${quote(hiragana)}
      ),
      '01345@$',
      'oieasas'
    ),
    '[^${keepClass}]',
    '',
    'g'
  )
$$;

-- False when the name contains a blocked term. "contains" terms are matched in
-- the skeleton; "tokens" only as whole ASCII words.
create or replace function public.is_name_allowed(p_name text)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select
    not exists (
      select 1
      from unnest(
        ${array(flatten(terms.contains))}
      ) as blocked(term)
      where position(blocked.term in public.name_skeleton(p_name)) > 0
    )
    and not exists (
      select 1
      from regexp_split_to_table(
        translate(lower(normalize(coalesce(p_name, ''), NFKC)), '01345@$', 'oieasas'),
        '[^a-z0-9]+'
      ) as word(value)
      where word.value = any (
        ${array(flatten(terms.tokens))}
      )
    )
$$;`);
